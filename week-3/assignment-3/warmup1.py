
# Store a score in a variable
score = 84

# Print the score
print(f"Score: {score}")

# Check the score and print the matching letter grade
if score >= 90:
    print("Grade: A")
elif score >= 80:
    print("Grade: B")
elif score >= 70:
    print("Grade: C")
elif score >= 60:
    print("Grade: D")
else:
    print("Grade: F")

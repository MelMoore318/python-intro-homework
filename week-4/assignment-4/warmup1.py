# Warmup 1: List Operations

# Create a hardcoded list of 8 numbers
numbers = [10,20,30,40,50,60,70,80]

# Print the first item
print("First number:", numbers[0])

#Print the last number using a negative index
print("Last number:", numbers[-1])

#Print the middle four numbers using slicing
print("Middle four numbers:", numbers[2:6])

#Print the numbers in reverse order using slicing
print("Numbers in reverse order:", numbers[::-1])